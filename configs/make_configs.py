"""Write one BasicSR / NAFNet option file per (architecture, weather, condition, level, seed).

Option files hold no paths; data locations come from the SCENEWX_* environment variables.

  python configs/make_configs.py --thesis                      # the option files used in the thesis
  python configs/make_configs.py --weather fog --cells base full --levels moderate --seeds 10 11
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
from scenewx import cells as CELLS                                             # noqa: E402

TEMPLATE = """# SceneWx condition: {weather} / {cell} / {level}, crop {crop}, {iters} iters, seed {seed}.
# Generated by configs/make_configs.py. Severity-matched by calibration/calibration_cells.json
# (target {target:.4f}, {source}).
# No datasets.val block on purpose (NAFNet's train.py single-GPU validation crash).
name: {name}
model_type: ImageRestorationModel
scale: 1
num_gpu: 1
manual_seed: {seed}

datasets:
  train:
    name: {name}-train
    type: SceneWxPairedDataset
    weather: {weather}
    cell: {cell}
    level: {level}
    split: train
    seed: {seed}
    gt_size: {crop}
    phase: train
    io_backend:
      type: disk
    use_shuffle: true
    num_worker_per_gpu: 6
    batch_size_per_gpu: 4
    dataset_enlarge_ratio: 1
    prefetch_mode: ~

{network_g}

path:
  pretrain_network_g: ~
  strict_load_g: true
  resume_state: ~

train:
  optim_g:
    type: AdamW
    lr: !!float {lr}
    weight_decay: 0.
    betas: [0.9, 0.9]
  scheduler:
    type: TrueCosineAnnealingLR
    T_max: {iters}
    eta_min: !!float 1e-7
  total_iter: {iters}
  warmup_iter: -1
  pixel_opt:
    type: PSNRLoss
    loss_weight: 1
    reduction: mean

logger:
  print_freq: 200
  save_checkpoint_freq: !!float {ckpt}
  use_tb_logger: false
  wandb:
    project: ~
    resume_id: ~

dist_params:
  backend: nccl
  port: 29491
"""

NETS = {
    'nafnet': ('network_g:\n  type: NAFNet\n  width: 32\n  enc_blk_nums: [2, 2, 4, 8]\n  middle_blk_num: 12\n  dec_blk_nums: [2, 2, 2, 2]', '1e-3'),
    # Restormer "light" (basicsr_plugins/Restormer_arch.py), lr 3e-4
    'restormer': ('network_g:\n  type: Restormer\n  dim: 32\n  num_blocks: [2, 3, 3, 4]\n  num_refinement_blocks: 2\n  heads: [1, 2, 4, 8]\n  ffn_expansion_factor: 2.66\n  bias: false\n  LayerNorm_type: WithBias', '3e-4'),
}

# option files used in the thesis (crop 256, 60k iterations)
THESIS = (
    [('nafnet', w, c, 'moderate', 10) for w in ('fog', 'rain', 'snow') for c in CELLS.cells_for(w)]
    + [('nafnet', w, 'full', l, 10) for w in ('fog', 'rain', 'snow') for l in ('light', 'heavy', 'mixed')]
    + [('nafnet', 'rain', c, 'moderate', 20) for c in ('P2', 'full', 'scrambled')]
    + [('restormer', 'fog', c, 'moderate', 10) for c in ('base', 'full', 'scrambled')]
    + [('restormer', 'fog', 'full', 'light', 10)]
    + [('restormer', 'snow', c, 'moderate', 10) for c in ('base', 'P2', 'full', 'scrambled')]
)


def write(arch, weather, cell, level, seed, crop=256, iters=60000, out=None):
    out = out or os.path.join(HERE, arch)
    cal = CELLS.load_cell_calibration()[weather]
    lv = level if level != 'mixed' else 'moderate'
    name = CELLS.opt_name(weather, cell, level, crop, iters, seed, arch=arch)
    net, lr = NETS[arch]
    os.makedirs(out, exist_ok=True)
    with open(f'{out}/{name}.yml', 'w') as f:
        f.write(TEMPLATE.format(name=name, weather=weather, cell=cell, level=level, crop=crop,
                                iters=iters, seed=seed, ckpt=iters // 4, network_g=net, lr=lr,
                                target=cal[lv]['target_severity'], source=cal[lv]['target_source']))
    return name


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--thesis', action='store_true', help='write the option files used in the thesis')
    ap.add_argument('--arch', default='nafnet', choices=list(NETS))
    ap.add_argument('--weather', action='append', default=None)
    ap.add_argument('--cells', nargs='+', default=None)
    ap.add_argument('--levels', nargs='+', default=['moderate'])
    ap.add_argument('--crop', type=int, default=256)
    ap.add_argument('--iters', type=int, default=60000)
    ap.add_argument('--seeds', type=int, nargs='+', default=[10])
    ap.add_argument('--out', default=None, help='output folder (default: configs/<arch>)')
    a = ap.parse_args()
    names = []
    if a.thesis:
        names = [write(*spec, out=a.out) for spec in THESIS]
    else:
        for w in (a.weather or ['fog', 'rain', 'snow']):
            for c in (a.cells or CELLS.cells_for(w)):
                for l in a.levels:
                    for s in a.seeds:
                        names.append(write(a.arch, w, c, l, s, a.crop, a.iters, out=a.out))
    print(f'wrote {len(names)} option files')
    for n in names:
        print('  ', n)
